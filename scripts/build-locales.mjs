/** Deep clone with leaf translation via callback */
function mapLeaves(obj, fn) {
  if (obj === null || typeof obj !== "object") return fn(obj);
  if (Array.isArray(obj)) return obj.map((v) => mapLeaves(v, fn));
  const out = {};
  for (const [k, v] of Object.entries(obj)) {
    out[k] = mapLeaves(v, fn);
  }
  return out;
}

